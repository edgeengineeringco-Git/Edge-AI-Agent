PAD_NAMES = ["PAD_K_A.spc", "PAD_U_A.spc", "PAD_Th_A.spc"]
PAD_TEXTS = [PAD_K_A_SPC, PAD_U_A_SPC, PAD_TH_A_SPC]
PAD_LABELS = ["PAD_K_A", "PAD_U_A", "PAD_Th_A"]
HEADER_LINES = 2
N_CHANNELS = 1024
EXPECTED_LINES = HEADER_LINES + N_CHANNELS  # 1026


def ensure_pad_dir(output_dir: str) -> str:
    """Write all three PAD .spc files to output_dir from embedded data.

    Args:
        output_dir: Directory path to write PAD files into.

    Returns:
        The output_dir path on success.

    Raises:
        RuntimeError: If any PAD data is malformed or file writing fails.
    """
    from pathlib import Path

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    for name, text in zip(PAD_NAMES, PAD_TEXTS):
        lines = text.strip("\n").splitlines()
        if len(lines) < EXPECTED_LINES:
            raise RuntimeError(
                f"Embedded PAD {name}: got {len(lines)} lines, "
                f"expected at least {EXPECTED_LINES} (2 header + {N_CHANNELS} channels). "
                "PAD data may be corrupted or truncated."
            )
        # Validate header lines parse as numbers
        try:
            float(lines[0].strip().split()[0])
            float(lines[1].strip().split()[0])
        except (ValueError, IndexError) as exc:
            raise RuntimeError(
                f"Embedded PAD {name}: header lines 1-2 must be numeric. "
                f"Line 1: {lines[0]!r}, Line 2: {lines[1]!r}. Error: {exc}"
            )
        # Validate channel lines (spot-check first and last 5)
        for idx in list(range(2, 7)) + list(range(2 + N_CHANNELS - 5, 2 + N_CHANNELS)):
            try:
                float(lines[idx].strip().split()[0])
            except (ValueError, IndexError) as exc:
                raise RuntimeError(
                    f"Embedded PAD {name}: channel line {idx + 1} is not numeric: "
                    f"{lines[idx]!r}. Error: {exc}"
                )
        # Write file
        out_path = out / name
        out_path.write_text("\n".join(lines[:EXPECTED_LINES]) + "\n", encoding="utf-8")
        file_size = out_path.stat().st_size
        if file_size == 0:
            raise RuntimeError(f"Failed to write {out_path}: file is empty.")

    return output_dir


def validate_pad_dir(pad_dir: str) -> bool:
    """Validate that a directory contains all three PAD files with correct structure.

    Args:
        pad_dir: Directory path to check.

    Returns:
        True if all PAD files are present and structurally valid.

    Raises:
        FileNotFoundError: If any PAD file is missing.
        RuntimeError: If a PAD file has wrong line count or unparseable data.
    """
    from pathlib import Path

    pad_path = Path(pad_dir)
    if not pad_path.is_dir():
        raise FileNotFoundError(f"PAD directory not found: {pad_dir}")

    for name in PAD_NAMES:
        spc_path = pad_path / name
        if not spc_path.is_file():
            raise FileNotFoundError(f"PAD file missing: {spc_path}")

        lines = spc_path.read_text(encoding="utf-8", errors="ignore").splitlines()
        if len(lines) < EXPECTED_LINES:
            raise RuntimeError(
                f"PAD file {name}: got {len(lines)} lines, "
                f"expected at least {EXPECTED_LINES}."
            )
        try:
            float(lines[0].strip().split()[0])
            float(lines[1].strip().split()[0])
            for i in range(2, 2 + N_CHANNELS):
                float(lines[i].strip().split()[0])
        except (ValueError, IndexError) as exc:
            raise RuntimeError(
                f"PAD file {name}: unparseable data at line {i + 1}: "
                f"{lines[i]!r}. Error: {exc}"
            )

    return True
